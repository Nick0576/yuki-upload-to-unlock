#!/usr/bin/env bash
# Build a signed, standalone Yuki APK without Gradle.
#
# Needs: node, JDK 17+, and the Debian/Ubuntu packages `aapt apksigner zipalign`
# plus an `android.jar` (package `android-sdk-platform-23`).
# The dexer (r8.jar) is downloaded once into android/tools/.
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT=$PWD

# aapt (build-tools 29) can only parse the older framework resource table, so
# resources link against API 23 while Java compiles against the modern stubs.
RES_JAR=${RES_JAR:-/usr/lib/android-sdk/platforms/android-23/android.jar}
ANDROID_JAR=${ANDROID_JAR:-$ROOT/android/tools/android-35.jar}
R8_JAR=${R8_JAR:-$ROOT/android/tools/r8.jar}
R8_URL="https://dl.google.com/dl/android/maven2/com/android/tools/r8/9.5.32/r8-9.5.32.jar"
PLATFORM_URL="https://dl.google.com/android/repository/platform-35_r02.zip"

OUT=$ROOT/android/build
KEYSTORE=${KEYSTORE:-$ROOT/android/yuki.keystore}
KS_PASS=${KS_PASS:-yuki-release}
KS_ALIAS=${KS_ALIAS:-yuki}
APK_NAME=${APK_NAME:-Yuki.apk}

need() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "Missing '$1'. Install it first (see the header of this script)." >&2
    exit 1
  }
}

need node
need javac
need aapt
need apksigner
need zipalign
need keytool

if [ ! -f "$ANDROID_JAR" ]; then
  echo "→ downloading android.jar (API 35)…"
  mkdir -p "$(dirname "$ANDROID_JAR")"
  tmp=$(mktemp -d)
  curl -fsSL --retry 2 -o "$tmp/platform.zip" "$PLATFORM_URL"
  unzip -q -o "$tmp/platform.zip" 'android-35/android.jar' -d "$tmp"
  mv "$tmp/android-35/android.jar" "$ANDROID_JAR"
  rm -rf "$tmp"
fi

if [ ! -f "$R8_JAR" ]; then
  echo "→ downloading r8.jar (dexer)…"
  mkdir -p "$(dirname "$R8_JAR")"
  curl -fsSL --retry 2 -o "$R8_JAR" "$R8_URL"
fi

if [ ! -f "$ROOT/.env" ]; then
  echo "Missing .env (NOMI_API_KEY / KOOLBASE_SECRET_KEY)" >&2
  exit 1
fi

echo "→ building web app"
npm run build --silent

echo "→ packing assets"
rm -rf "$OUT"
mkdir -p "$OUT/classes" "$OUT/dex" "$OUT/gen" "$OUT/apk" "$ROOT/android/assets/www"
rm -rf "$ROOT/android/assets/www"
mkdir -p "$ROOT/android/assets/www"
cp -r "$ROOT/dist/." "$ROOT/android/assets/www/"

echo "→ writing API keys into the app"
node - <<'NODE'
const fs = require('fs')
const env = {}
for (const line of fs.readFileSync('.env', 'utf8').split('\n')) {
  const s = line.trim()
  if (!s || s.startsWith('#')) continue
  const i = s.indexOf('=')
  if (i < 0) continue
  env[s.slice(0, i).trim()] = s.slice(i + 1).trim().replace(/^["']|["']$/g, '')
}
const q = (v) => JSON.stringify(v || '')
const src = `package com.heartverse.yuki;

/** Generated by scripts/build-apk.sh — never commit. */
final class BuildKeys {
  static final String NOMI_API_KEY = ${q(env.NOMI_API_KEY)};
  static final String KOOLBASE_SECRET_KEY = ${q(env.KOOLBASE_SECRET_KEY || env.KOOLBASE_API_KEY)};

  private BuildKeys() {}
}
`
fs.writeFileSync('android/java/com/heartverse/yuki/BuildKeys.java', src)
NODE

echo "→ compiling resources"
[ -f "$RES_JAR" ] || {
  echo "Missing $RES_JAR (apt-get install -y android-sdk-platform-23)" >&2
  exit 1
}
aapt package -f -m -J "$OUT/gen" -M android/AndroidManifest.xml -S android/res -I "$RES_JAR"
aapt package -f -M android/AndroidManifest.xml -S android/res -A android/assets -I "$RES_JAR" -F "$OUT/apk/base.apk"

echo "→ compiling java"
javac -source 8 -target 8 -Xlint:-options \
  -bootclasspath "$ANDROID_JAR" \
  -d "$OUT/classes" \
  $(find android/java "$OUT/gen" -name '*.java')

echo "→ dexing"
java -cp "$R8_JAR" com.android.tools.r8.D8 \
  --release --min-api 23 \
  --lib "$ANDROID_JAR" \
  --output "$OUT/dex" \
  $(find "$OUT/classes" -name '*.class')

(cd "$OUT/dex" && zip -qj "$OUT/apk/base.apk" classes.dex)

echo "→ aligning + signing"
zipalign -f 4 "$OUT/apk/base.apk" "$OUT/apk/aligned.apk"

if [ ! -f "$KEYSTORE" ]; then
  keytool -genkeypair -keystore "$KEYSTORE" -storetype PKCS12 \
    -storepass "$KS_PASS" -keypass "$KS_PASS" -alias "$KS_ALIAS" \
    -keyalg RSA -keysize 2048 -validity 10000 \
    -dname "CN=Yuki, OU=Heartverse, O=Heartverse, L=Manila, ST=Metro Manila, C=PH"
fi

mkdir -p "$ROOT/apk"
apksigner sign --ks "$KEYSTORE" --ks-key-alias "$KS_ALIAS" \
  --ks-pass "pass:$KS_PASS" --key-pass "pass:$KS_PASS" \
  --out "$ROOT/apk/$APK_NAME" "$OUT/apk/aligned.apk"
apksigner verify --print-certs "$ROOT/apk/$APK_NAME" | head -4

BADGING=$(aapt dump badging "$ROOT/apk/$APK_NAME" | head -2)
echo "$BADGING"
echo
echo "✓ APK: $ROOT/apk/$APK_NAME"
ls -lh "$ROOT/apk/$APK_NAME"
